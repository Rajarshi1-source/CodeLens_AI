"""CodeLens AI review-quality eval runner.

Loads testset.jsonl (generated by build_testset.py), sends each diff (plus its repository context files)
to the backend, and scores:

  * precision / recall / F1 on the planted bugs, matched on (file, line) and minimum severity;
  * must_not_flag hits — comments on lines a good reviewer has to leave alone;
  * cross-file recall — planted bugs that are only visible with repository context (G1 retrieval);
  * risk accuracy — whether the PR risk band (G3) matches the expected one;
  * mean tokens per review — the cost signal.

--ci enforces absolute floors plus no-regression against baseline.json, including a COST gate (mean tokens
per review may not grow more than 20% over the baseline). --ablate-retrieval re-runs the cross-file cases
without repository context and requires that context actually helps. --save-baseline re-baselines
deliberately (commit the new baseline.json together with the change that moved the numbers).

Examples:
    python run_eval.py --base-url http://localhost:8080
    python run_eval.py --ci --ablate-retrieval
    python run_eval.py --save-baseline
"""

from __future__ import annotations

import argparse
import json
import os
import sys

from eval_types import CaseResult, Metrics, ReviewResult, TestCase
from reviewer_client import ReviewerClient

HERE = os.path.dirname(os.path.abspath(__file__))
TESTSET = os.path.join(HERE, "testset.jsonl")
BASELINE = os.path.join(HERE, "baseline.json")

# Absolute quality floors for the CI gate.
MIN_PRECISION = 0.80
MIN_RECALL = 0.80
MIN_CROSS_FILE_RECALL = 0.80
MIN_RISK_ACCURACY = 0.80
# Allowed drop vs. baseline before we call it a regression.
REGRESSION_TOLERANCE = 0.05
# Cost-regression gate: mean tokens per review may grow at most this much over the baseline.
MAX_TOKEN_GROWTH = 0.20


def load_testset(path: str) -> list[TestCase]:
    cases = []
    with open(path, "r", encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if line:
                cases.append(TestCase.from_json(json.loads(line)))
    return cases


def score_case(case: TestCase, review: ReviewResult) -> CaseResult:
    comments = review.comments
    result = CaseResult(case_id=case.id, category=case.category, comments=comments,
                        cross_file=case.is_cross_file, tokens=review.total_tokens,
                        expected_risk=case.expected_risk, risk_level=review.risk_level)

    accounted: set[int] = set()  # indexes of comments explained by an expected finding
    for expected in case.expected_findings:
        hits = [i for i, c in enumerate(comments) if expected.anchors(c)]
        accounted.update(hits)
        if any(expected.satisfied_by(comments[i].severity) for i in hits):
            result.true_positives += 1
        else:
            result.false_negatives += 1

    for i, comment in enumerate(comments):
        if i in accounted:
            continue
        result.false_positives += 1
        if any(a.anchors(comment) for a in case.must_not_flag):
            result.must_not_flag_hits += 1
    return result


def run(client: ReviewerClient, cases: list[TestCase], retrieval: bool = True) -> list[CaseResult]:
    return [score_case(case, client.review_diff(case.diff, case.language, case.context_files, retrieval))
            for case in cases]


def print_report(results: list[CaseResult], metrics: Metrics, title: str = "review-quality eval") -> None:
    print(f"\nCodeLens AI — {title}")
    print("=" * 84)
    print(f"{'case':<28}{'cat':<13}{'TP':>4}{'FP':>4}{'FN':>4}{'MNF':>5}{'tokens':>8}  risk")
    print("-" * 84)
    for r in results:
        risk = r.risk_level or "-"
        if r.expected_risk and r.expected_risk != r.risk_level:
            risk += f" (expected {r.expected_risk})"
        print(f"{r.case_id:<28}{r.category:<13}{r.true_positives:>4}{r.false_positives:>4}"
              f"{r.false_negatives:>4}{r.must_not_flag_hits:>5}{r.tokens:>8}  {risk}")
    print("-" * 84)
    print(f"precision={metrics.precision:.3f}  recall={metrics.recall:.3f}  f1={metrics.f1:.3f}  "
          f"(TP={metrics.true_positives} FP={metrics.false_positives} FN={metrics.false_negatives})")
    print(f"cross_file_recall={metrics.cross_file_recall:.3f}  must_not_flag_hits={metrics.must_not_flag_hits}  "
          f"risk_accuracy={metrics.risk_accuracy:.3f}  mean_tokens_per_review={metrics.mean_tokens_per_review:.1f}")
    print("=" * 84)


def load_baseline() -> dict | None:
    if not os.path.exists(BASELINE):
        return None
    with open(BASELINE, "r", encoding="utf-8") as fh:
        return json.load(fh)


def save_baseline(metrics: Metrics) -> None:
    with open(BASELINE, "w", encoding="utf-8", newline="\n") as fh:
        json.dump(metrics.to_json(), fh, indent=2)
        fh.write("\n")
    print(f"Saved baseline -> {BASELINE}")


def gate_failures(metrics: Metrics, baseline: dict | None, ablated: Metrics | None = None) -> list[str]:
    """Every reason the CI gate fails (empty = pass). Pure, so it is unit tested in test_scoring.py."""
    fails: list[str] = []
    if metrics.precision < MIN_PRECISION:
        fails.append(f"precision {metrics.precision:.3f} < {MIN_PRECISION}")
    if metrics.recall < MIN_RECALL:
        fails.append(f"recall {metrics.recall:.3f} < {MIN_RECALL}")
    if metrics.cross_file_recall < MIN_CROSS_FILE_RECALL:
        fails.append(f"cross-file recall {metrics.cross_file_recall:.3f} < {MIN_CROSS_FILE_RECALL}")
    if metrics.risk_accuracy < MIN_RISK_ACCURACY:
        fails.append(f"risk accuracy {metrics.risk_accuracy:.3f} < {MIN_RISK_ACCURACY}")

    if ablated is not None and metrics.cross_file_recall <= ablated.cross_file_recall:
        fails.append(f"repository context does not help: cross-file recall {metrics.cross_file_recall:.3f} "
                     f"with retrieval vs {ablated.cross_file_recall:.3f} without")

    if baseline:
        for key in ("precision", "recall", "cross_file_recall", "risk_accuracy"):
            if key in baseline and getattr(metrics, key) < baseline[key] - REGRESSION_TOLERANCE:
                fails.append(f"{key} regressed {baseline[key]:.3f} -> {getattr(metrics, key):.3f}")
        if metrics.must_not_flag_hits > baseline.get("must_not_flag_hits", 0):
            fails.append(f"must_not_flag hits rose {baseline.get('must_not_flag_hits', 0)} -> "
                         f"{metrics.must_not_flag_hits}")
        base_tokens = baseline.get("mean_tokens_per_review")
        if base_tokens and metrics.mean_tokens_per_review > base_tokens * (1 + MAX_TOKEN_GROWTH):
            fails.append(f"COST regression: mean tokens/review {base_tokens:.1f} -> "
                         f"{metrics.mean_tokens_per_review:.1f} (> +{MAX_TOKEN_GROWTH:.0%}); "
                         "re-baseline deliberately with --save-baseline if this is intended")
    return fails


def main() -> int:
    parser = argparse.ArgumentParser(description="CodeLens AI review-quality eval")
    parser.add_argument("--base-url", default=os.environ.get("CODELENS_BASE_URL", "http://localhost:8080"))
    parser.add_argument("--ci", action="store_true", help="enforce floors + no-regression + cost gate; exit 1 on fail")
    parser.add_argument("--ablate-retrieval", action="store_true",
                        help="also run the cross-file cases without repository context and require context to help")
    parser.add_argument("--save-baseline", action="store_true", help="write current metrics to baseline.json")
    parser.add_argument("--json", metavar="PATH", help="write per-case results + metrics as JSON")
    args = parser.parse_args()

    client = ReviewerClient(args.base_url)
    if not client.health():
        print(f"Backend not reachable / unhealthy at {args.base_url}")
        return 2

    cases = load_testset(TESTSET)
    results = run(client, cases)
    metrics = Metrics.compute(results)
    print_report(results, metrics)

    ablated: Metrics | None = None
    if args.ablate_retrieval:
        xf_cases = [c for c in cases if c.is_cross_file and not c.is_clean]
        ablated_results = run(client, xf_cases, retrieval=False)
        ablated = Metrics.compute(ablated_results)
        print_report(ablated_results, ablated, "ablation: cross-file cases WITHOUT repository context")

    if args.json:
        with open(args.json, "w", encoding="utf-8") as fh:
            json.dump({"metrics": metrics.to_json(),
                       "ablated": ablated.to_json() if ablated else None,
                       "cases": [{"id": r.case_id, "tp": r.true_positives, "fp": r.false_positives,
                                  "fn": r.false_negatives, "mnf": r.must_not_flag_hits, "tokens": r.tokens,
                                  "risk": r.risk_level, "expected_risk": r.expected_risk} for r in results]},
                      fh, indent=2)

    if args.save_baseline:
        save_baseline(metrics)

    if args.ci:
        fails = gate_failures(metrics, load_baseline(), ablated)
        for f in fails:
            print(f"GATE FAIL: {f}")
        if fails:
            return 1
        print("GATE PASS")
    return 0


if __name__ == "__main__":
    sys.exit(main())
